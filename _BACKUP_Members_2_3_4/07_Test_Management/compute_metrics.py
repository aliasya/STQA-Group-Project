"""
Week 8 - Test metrics (BACKUP for Member 4, Defect & Metrics Coordinator)

1. Re-runs every automated suite with --junitxml (unless --no-run)
2. Reads the black-box CSV and the manual test tables (GUI, usability, accessibility)
3. Reads defect_log.csv
4. Writes Metrics.md, Defect_Log.md and two charts (PNG)

Run from repo root:   python _BACKUP_Members_2_3_4/07_Test_Management/compute_metrics.py
"""
import csv
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import Counter, OrderedDict
from datetime import date

HERE = os.path.dirname(os.path.abspath(__file__))
def _find_repo_root(start):
    """Walk up until we find app/app.py, so the script works from the main folder or the backup folder."""
    d = start
    while not os.path.exists(os.path.join(d, "app", "app.py")):
        parent = os.path.dirname(d)
        if parent == d:
            raise SystemExit("Run this inside the PyTodo-Pro-QA repository")
        d = parent
    return d


ROOT = _find_repo_root(HERE)
# Where the black-box CSV lives: backup folder if present, else main folder
B = os.path.join(ROOT, "_BACKUP_Members_2_3_4") if os.path.exists(
    os.path.join(ROOT, "_BACKUP_Members_2_3_4", "01_Black_Box", "blackbox_results.csv")) else ROOT
RES = os.path.join(HERE, "results")
os.makedirs(RES, exist_ok=True)

SUITES = OrderedDict([
    ("White-box unit (Wk2)", "_BACKUP_Members_2_3_4/02_White_Box_Coverage"),
    ("API (Wk4)", "_BACKUP_Members_2_3_4/04_Web_API"),
    ("Security (Wk5)", "05_Security_Performance/Security"),
    ("Regression + Selenium UI (Wk6)", "_BACKUP_Members_2_3_4/06_Automation_Regression"),
])
MANUAL = OrderedDict([
    ("GUI checklist (Wk3)", "03_Special_Testing/GUI_Compatibility/GUI_Compatibility_Report.md"),
    ("Usability + accessibility (Wk3)", "_BACKUP_Members_2_3_4/03_Special_Testing/Usability_Accessibility/Usability_Accessibility_Report.md"),
    ("Performance (Wk5)", "_BACKUP_Members_2_3_4/05_Security_Performance/Performance/Performance_Report.md"),
])


def run_suites():
    for name, path in SUITES.items():
        out = os.path.join(RES, re.sub(r"\W+", "_", name).strip("_") + ".xml")
        subprocess.run([sys.executable, "-m", "pytest", path, "-q", "-p", "no:cacheprovider",
                        "-p", "no:logging", f"--junitxml={out}"], cwd=ROOT,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def junit_counts(name):
    f = os.path.join(RES, re.sub(r"\W+", "_", name).strip("_") + ".xml")
    c = Counter()
    for tc in ET.parse(f).iter("testcase"):
        if tc.find("failure") is not None or tc.find("error") is not None:
            c["Fail"] += 1
        elif tc.find("skipped") is not None:
            msg = tc.find("skipped").get("type", "") + tc.find("skipped").get("message", "")
            c["XFail" if "xfail" in msg.lower() else "Not Run"] += 1
        else:
            c["Pass"] += 1
    return c


def md_counts(path):
    c = Counter()
    for line in open(os.path.join(ROOT, path), encoding="utf-8"):
        if re.match(r"\|\s*TC-[A-Z]+-\d+", line):
            cells = [x.strip() for x in line.strip().strip("|").split("|")]
            cell = cells[9] if len(cells) >= 12 else ""          # 'Status' column of the template
            status = next((s for s in ("Pass", "Fail", "Blocked", "Not Run") if cell.startswith(s)), "Not Run")
            c[status] += 1
    return c


def main():
    if "--no-run" not in sys.argv:
        run_suites()
    rows = []
    bb = Counter(r["status"] for r in csv.DictReader(open(os.path.join(B, "01_Black_Box", "blackbox_results.csv"), encoding="utf-8")))
    rows.append(("Black-box (Wk1)", bb))
    for name in list(SUITES)[:2]:
        rows.append((name, junit_counts(name)))
    rows.append((list(MANUAL)[0], md_counts(MANUAL["GUI checklist (Wk3)"])))
    rows.append((list(MANUAL)[1], md_counts(MANUAL["Usability + accessibility (Wk3)"])))
    rows.append(("Security (Wk5)", junit_counts("Security (Wk5)")))
    if os.path.exists(os.path.join(ROOT, MANUAL["Performance (Wk5)"])):
        rows.append(("Performance (Wk5)", md_counts(MANUAL["Performance (Wk5)"])))
    reg = junit_counts("Regression + Selenium UI (Wk6)")

    L = [f"# Test Metrics (Week 8) – generated {date.today().isoformat()}", "",
         "Generated by `compute_metrics.py` from the actual execution results. Automated counts are per **execution** "
         "(parameterised tests count once per parameter set). Manual counts are per test case.", "",
         "## 1. Execution status by test level", "",
         "| Test level / type | Planned | Executed | Passed | Failed | Blocked | Not Run | Pass rate (of executed) |",
         "|---|---|---|---|---|---|---|---|"]
    T = Counter()
    for name, c in rows:
        ex = c["Pass"] + c["Fail"]
        planned = ex + c["Blocked"] + c["Not Run"]
        T.update({"planned": planned, "ex": ex, "Pass": c["Pass"], "Fail": c["Fail"], "Blocked": c["Blocked"], "Not Run": c["Not Run"]})
        L.append(f"| {name} | {planned} | {ex} | {c['Pass']} | {c['Fail']} | {c['Blocked']} | {c['Not Run']} | {c['Pass'] / ex:.1%} |")
    L.append(f"| **Total (detection testing)** | **{T['planned']}** | **{T['ex']}** | **{T['Pass']}** | **{T['Fail']}** | "
             f"**{T['Blocked']}** | **{T['Not Run']}** | **{T['Pass'] / T['ex']:.1%}** |")
    L += ["", f"- **Execution rate** = executed / planned = {T['ex']}/{T['planned']} = **{T['ex'] / T['planned']:.1%}**",
          f"- **Pass rate** = passed / executed = {T['Pass']}/{T['ex']} = **{T['Pass'] / T['ex']:.1%}**",
          f"- **Fail rate** = failed / executed = {T['Fail']}/{T['ex']} = **{T['Fail'] / T['ex']:.1%}**", "",
          "### Regression suite (Week 6) – reported separately",
          "", "| Executions | Passed | Known-defect XFAIL | Unexpected failures |", "|---|---|---|---|",
          f"| {sum(reg.values())} | {reg['Pass']} | {reg['XFail']} | {reg['Fail']} |", "",
          "XFAIL = test asserts correct behaviour and fails because of an **open, logged** defect (strict mode). "
          "Unexpected failures = 0 means no new regressions.", "",
          "### Compatibility configurations (Week 3)", "",
          "| Planned configurations | Executed | Not run |", "|---|---|---|", "| 6 (CFG-01 – CFG-06) | 2 | 4 |", ""]

    D = list(csv.DictReader(open(os.path.join(HERE, "defect_log.csv"), encoding="utf-8")))
    sev_order = ["Critical", "Major", "Moderate", "Minor"]
    sev = Counter(d["severity"] for d in D)
    pri = Counter(d["priority"] for d in D)
    L += ["## 2. Defects by severity and priority", "", "| Severity | High | Medium | Low | Total |", "|---|---|---|---|---|"]
    for s in sev_order:
        pc = Counter(d["priority"] for d in D if d["severity"] == s)
        L.append(f"| {s} | {pc['High']} | {pc['Medium']} | {pc['Low']} | {sev[s]} |")
    L.append(f"| **Total** | **{pri['High']}** | **{pri['Medium']}** | **{pri['Low']}** | **{len(D)}** |")

    def area(d):
        f = d["feature"].lower()
        for key, lab in [("access", "Usability & accessibility"), ("usability", "Usability & accessibility"),
                         ("gui", "GUI & compatibility"), ("search", "Search / filter"), ("delete", "Task CRUD"), ("create", "Task CRUD"), ("update", "Task CRUD"),
                         ("edit", "Task CRUD"), ("list tasks", "Search / filter"), ("regist", "Accounts & login"),
                         ("login", "Accounts & login"), ("urgency", "Urgency & dashboard"), ("dashboard", "Urgency & dashboard"),
                         ("access", "Usability & accessibility"), ("usability", "Usability & accessibility"),
                         ("gui", "GUI & compatibility"), ("configuration", "Security configuration"),
                         ("web forms", "Security configuration"), ("task list (web ui)", "Task list UI (XSS)")]:
            if key in f:
                return lab
        return "Other"
    mod = Counter(area(d) for d in D)
    L += ["", "## 3. Defects by feature area", "", "| Feature area | Critical | Major | Moderate | Minor | Total |", "|---|---|---|---|---|---|"]
    for m, n in mod.most_common():
        sc = Counter(d["severity"] for d in D if area(d) == m)
        L.append(f"| {m} | {sc['Critical']} | {sc['Major']} | {sc['Moderate']} | {sc['Minor']} | {n} |")
    phase = Counter(d["phase"].split(" ")[0] + " " + d["phase"].split(" ")[1] if " " in d["phase"] else d["phase"] for d in D)
    by = Counter(d["found_by"] for d in D)
    L += ["", "## 4. Defects by detecting activity", "", "| Member / activity | Defects |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in sorted(by.items())]
    loc = 0
    for f in ("app.py", "helpers.py"):
        loc += sum(1 for line in open(os.path.join(ROOT, "app", f)) if line.strip() and not line.strip().startswith("#"))
    L += ["", "## 5. Derived indicators", "",
          f"- **Defect density** = {len(D)} defects / {loc / 1000:.2f} KLOC (non-blank, non-comment Python) = **{len(D) / (loc / 1000):.1f} defects/KLOC**. "
          "Templates/CSS defects included in the numerator, so this slightly overstates code density.",
          f"- **Critical + Major share** = {sev['Critical'] + sev['Major']}/{len(D)} = **{(sev['Critical'] + sev['Major']) / len(D):.0%}**",
          f"- **Open defects** = {sum(d['status'] == 'Open' for d in D)} / {len(D)} (we do not fix the app, so none can be closed)",
          "- **Defect removal efficiency** is not measurable: no fixes and no field data exist.", "",
          "Charts: `defects_by_severity.png`, `defects_by_area.png`.", ""]
    open(os.path.join(HERE, "Metrics.md"), "w", encoding="utf-8").write("\n".join(L))

    # Defect_Log.md (full)
    esc = lambda s: s.replace("|", "\\|")  # noqa: E731
    DL = ["# Consolidated Defect Log", "", "Single source: `defect_log.csv`. Severity/priority definitions: `07_Test_Management/Team_Conventions.md`.", "",
          "| Defect ID | Title | Affected Feature | Environment | Preconditions | Steps to Reproduce | Expected Result | Actual Result | Severity | Priority | Evidence | Status | Found by |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for d in D:
        DL.append("| " + " | ".join(esc(x) for x in [d["defect_id"], d["title"], f"{d['feature']} – `{d['module']}`", d["environment"],
                  d["preconditions"], d["steps"], d["expected"], d["actual"], d["severity"], d["priority"], d["evidence"],
                  d["status"], f"{d['found_by']} ({d['phase']})"]) + " |")
    open(os.path.join(HERE, "Defect_Log.md"), "w", encoding="utf-8").write("\n".join(DL) + "\n")

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        ink, ink2, surf = "#0b0b0b", "#52514e", "#fcfcfb"
        ramp = {"Minor": "#86b6ef", "Moderate": "#5598e7", "Major": "#2a78d6", "Critical": "#1c5cab"}

        def hbar(labels, values, colors, title, fname):
            fig, ax = plt.subplots(figsize=(6.4, 0.55 * len(labels) + 1.1), facecolor=surf)
            ax.set_facecolor(surf)
            y = range(len(labels))[::-1]
            ax.barh(list(y), values, color=colors, height=0.6)
            for yi, v in zip(y, values):
                ax.text(v + 0.1, yi, str(v), va="center", color=ink, fontsize=10)
            ax.set_yticks(list(y)); ax.set_yticklabels(labels, color=ink, fontsize=10)
            ax.set_xticks([]); ax.set_title(title, loc="left", color=ink, fontsize=12, pad=10)
            for s in ax.spines.values():
                s.set_visible(False)
            ax.tick_params(length=0)
            fig.tight_layout(); fig.savefig(os.path.join(HERE, fname), dpi=140); plt.close(fig)

        hbar(sev_order, [sev[s] for s in sev_order], [ramp[s] for s in sev_order],
             f"Defects by severity (n = {len(D)})", "defects_by_severity.png")
        ms = mod.most_common()
        hbar([m for m, _ in ms], [n for _, n in ms], ["#2a78d6"] * len(ms), "Defects by feature area", "defects_by_area.png")
    except ImportError:
        pass
    print("\n".join(L))


if __name__ == "__main__":
    main()
